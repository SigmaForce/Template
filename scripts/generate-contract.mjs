import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { buildContractDocument } from "../apps/api/dist/contract-document.js";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const contractDirectory = path.join(root, "packages", "api-client");
const openApiPath = path.join(contractDirectory, "openapi.json");
const schemaPath = path.join(
  contractDirectory,
  "src",
  "generated",
  "schema.ts",
);
const checkOnly = process.argv.includes("--check");

function sortObject(value) {
  if (Array.isArray(value)) {
    return value.map(sortObject);
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
        .map(([key, nestedValue]) => [key, sortObject(nestedValue)]),
    );
  }

  return value;
}

const document = sortObject(await buildContractDocument());
const openApiContents = `${JSON.stringify(document, null, 2)}\n`;
const schemaAst = await openapiTS(document, { silent: true });
const schemaContents = [
  "/**",
  " * Generated by `pnpm contract:generate`.",
  " * Do not edit this file directly.",
  " */",
  astToString(schemaAst).replaceAll("\r\n", "\n"),
].join("\n");

const artifacts = [
  [openApiPath, openApiContents],
  [schemaPath, schemaContents],
];

if (checkOnly) {
  const staleArtifacts = artifacts
    .filter(
      ([artifactPath, generatedContents]) =>
        !existsSync(artifactPath) ||
        readFileSync(artifactPath, "utf8") !== generatedContents,
    )
    .map(([artifactPath]) => path.relative(root, artifactPath));

  if (staleArtifacts.length > 0) {
    console.error(
      `Generated API contract is stale:\n- ${staleArtifacts.join("\n- ")}\nRun pnpm contract:generate and commit the result.`,
    );
    process.exit(1);
  }

  console.log("Generated API contract is up to date.");
} else {
  for (const [artifactPath, contents] of artifacts) {
    mkdirSync(path.dirname(artifactPath), { recursive: true });
    writeFileSync(artifactPath, contents);
  }

  console.log("Generated OpenAPI document and TypeScript schema.");
}
